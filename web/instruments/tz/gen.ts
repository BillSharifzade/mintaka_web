// Writes web/instruments/tz/data.ts from the system's IANA tz database.
//
//   node web/instruments/tz/gen.ts            (Node strips the types; no build step)
//
// Inputs (public domain): /usr/share/zoneinfo/zone1970.tab, zone.tab and the `L target alias`
// link lines of tzdata.zi. Output: zone → [lat, lon] (0.01°, about 1 km), alias → zone.
// Re-run after a tzdata update and commit the result; the page loads it only after the visitor
// presses "Measure my distance".

// @ts-ignore -- Node built-in; this repo carries no @types/node (the script runs in Node only).
import { readFileSync, writeFileSync } from 'node:fs';
import { buildTable, parseLinks, parseVersion, parseZoneTab, type LatLon } from './tzdb.ts';

const DIR = '/usr/share/zoneinfo/';
const read = (name: string): string => readFileSync(DIR + name, 'utf8') as string;

const zi = read('tzdata.zi');
const version = parseVersion(zi);
const { zones, aliases } = buildTable([parseZoneTab(read('zone1970.tab')), parseZoneTab(read('zone.tab'))], parseLinks(zi));

const round = (x: number): number => Math.round(x * 100) / 100;
const entries: [string, string][] = [];
for (const [zone, [lat, lon]] of zones as Map<string, LatLon>) entries.push([zone, `[${round(lat)},${round(lon)}]`]);
for (const [alias, zone] of aliases) entries.push([alias, JSON.stringify(zone)]);
entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const body = entries.map(([k, v]) => `${JSON.stringify(k)}:${v}`).join(',\n');
const out = `// GENERATED by web/instruments/tz/gen.ts — do not edit. Regenerate: node web/instruments/tz/gen.ts
// IANA tz database ${version} (public domain), read from /usr/share/zoneinfo: zone1970.tab and zone.tab
// (each zone's principal location) and the link lines of tzdata.zi (aliases).
// ${zones.size} zones → [latitude, longitude] in degrees, rounded to 0.01°; ${aliases.size} aliases → the zone they share.
import type { Table } from './tzdb.ts';

export const version = ${JSON.stringify(version)};

export const zones: Table = {
${body},
};
`;

writeFileSync(new URL('./data.ts', import.meta.url), out);
console.log(`tz ${version}: ${zones.size} zones, ${aliases.size} aliases → web/instruments/tz/data.ts (${out.length} bytes)`);
